CREATE TABLE IF NOT EXISTS tienda (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nombre text UNIQUE NOT NULL
);
CREATE TABLE IF NOT EXISTS producto (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku text UNIQUE NOT NULL, nombre text NOT NULL
);
CREATE TABLE IF NOT EXISTS inventario_tienda (
 tienda_id bigint REFERENCES tienda, producto_id bigint REFERENCES producto,
 pasillo text NOT NULL, stock_actual integer NOT NULL CHECK (stock_actual >= 0),
 stock_reservado integer NOT NULL DEFAULT 0 CHECK (stock_reservado BETWEEN 0 AND stock_actual),
 stock_disponible integer GENERATED ALWAYS AS (stock_actual - stock_reservado) STORED,
 PRIMARY KEY (tienda_id, producto_id)
);
CREATE TABLE IF NOT EXISTS pedido (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, referencia text UNIQUE NOT NULL,
 tienda_id bigint NOT NULL REFERENCES tienda, cliente text NOT NULL,
 modalidad text NOT NULL CHECK (modalidad IN ('RECOJO','DELIVERY')),
 estado text NOT NULL DEFAULT 'Recibido',
 creado timestamptz NOT NULL DEFAULT now(), compromiso timestamptz NOT NULL DEFAULT now() + interval '90 minutes',
 CHECK (estado IN ('Recibido','En picking','En packing','Listo','En reparto','Intento fallido','Entregado','Cancelado')),
 CHECK (modalidad = 'DELIVERY' OR estado NOT IN ('En reparto','Intento fallido'))
);
CREATE INDEX IF NOT EXISTS pedido_bandeja ON pedido (tienda_id, estado, compromiso);
CREATE TABLE IF NOT EXISTS detalle_pedido (
 pedido_id bigint REFERENCES pedido, producto_id bigint REFERENCES producto,
 cantidad integer NOT NULL CHECK (cantidad > 0), preparado boolean NOT NULL DEFAULT false,
 PRIMARY KEY (pedido_id, producto_id)
);
CREATE TABLE IF NOT EXISTS orden_picking (
 pedido_id bigint PRIMARY KEY REFERENCES pedido, inicio timestamptz, fin timestamptz
);
CREATE TABLE IF NOT EXISTS incidencia_stock (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, pedido_id bigint NOT NULL REFERENCES pedido,
